import { connect, sleep } from "./probe-lib.mjs";
const A = await connect({ name: "A", scopes: ["operator.read", "operator.write"] });
const atl = await A.call("sessions.create", { agentId: "atlas", label: `late-r ${Date.now()}` });
const pix = await A.call("sessions.create", { agentId: "pixel", label: `late-s ${Date.now()}` });
for (const k of [atl.key, pix.key]) await A.call("sessions.messages.subscribe", { key: k });
const t0 = Date.now();
const r = await A.send(pix.key, `#tool sessions_send ${JSON.stringify({ sessionKey: atl.key, message: "#slow 4 late", timeoutSeconds: 0 })}`);
await r.done; await sleep(12000);
const send = A.events.find((e) => e.t >= t0 && e.event === "agent" && e.payload?.data?.name === "sessions_send" && e.payload.data.phase === "result");
console.log("send result runId:", send.payload.data.result.details.runId);
const recRun = A.events.find((e) => e.t >= t0 && e.event === "agent" && e.payload?.sessionKey === atl.key && e.payload.stream === "lifecycle" && e.payload.data?.phase === "start");
console.log("recipient run id:", recRun?.payload.runId);
const h = await A.call("chat.history", { sessionKey: pix.key, limit: 20 });
const late = h.messages.find((m) => m.provenance?.kind === "inter_session");
console.log("late row:", JSON.stringify({ role: late.role, provenance: late.provenance, openclaw: late.__openclaw, keys: Object.keys(late) }).slice(0, 900));
const live = A.events.find((e) => e.t >= t0 && e.event === "session.message" && e.payload?.sessionKey === pix.key && e.payload.message?.provenance?.kind === "inter_session");
console.log("live session.message keys:", Object.keys(live?.payload ?? {}).join(","), "| message keys:", Object.keys(live?.payload.message ?? {}).join(","));
const u = await A.call("sessions.usage", { key: atl.key });
console.log("recipient usage row:", JSON.stringify(u.sessions?.[0] ?? {}).slice(0, 400));
await A.close();
