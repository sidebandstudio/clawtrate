import { connect, sleep, brief } from "./probe-lib.mjs";
const A = await connect({ name: "A", scopes: ["operator.read", "operator.write"] });
const ADM = await connect({ backend: true, scopes: ["operator.read", "operator.write", "operator.admin"] });
const r = (p, n = 700) => p.then((x) => "ok " + JSON.stringify(x).slice(0, n), (e) => `ERR ${e.gatewayCode ?? ""} ${e.message.slice(0, 250)}`);
const s = await A.call("sessions.create", { agentId: "atlas", label: `files ${Date.now()}` });
const key = s.key; await A.call("sessions.messages.subscribe", { key });
const t0 = Date.now();
const w = await A.send(key, '#tool write {"path":"notes/hello.txt","content":"hello from atlas\\n"}'); const wf = await w.done;
console.log("write run:", wf.state, JSON.stringify(wf.message?.content).slice(0, 200));
const tr = A.events.find((e) => e.t >= t0 && e.event === "agent" && e.payload?.stream === "tool" && e.payload?.data?.phase === "result");
console.log("write tool result:", JSON.stringify(tr?.payload?.data).slice(0, 400));
console.log("non-agent/chat events since:", [...new Set(A.events.filter((e) => e.t >= t0 && !["agent", "chat", "tick", "health"].includes(e.event)).map((e) => e.event))].join(","));
console.log("sessions.files.list:", await r(A.call("sessions.files.list", { sessionKey: key }), 1200));
console.log("sessions.files.get:", await r(A.call("sessions.files.get", { sessionKey: key, path: "notes/hello.txt" })));
console.log("workspace.list root:", await r(A.call("agents.workspace.list", { agentId: "atlas" }), 900));
console.log("workspace.list notes:", await r(A.call("agents.workspace.list", { agentId: "atlas", path: "notes" })));
console.log("workspace.get:", await r(A.call("agents.workspace.get", { agentId: "atlas", path: "notes/hello.txt" })));
console.log("sessions.diff:", await r(A.call("sessions.diff", { sessionKey: key })));
console.log("artifacts.list agentId only:", await r(A.call("artifacts.list", { agentId: "atlas" })));
console.log("artifacts.list session:", await r(A.call("artifacts.list", { sessionKey: key })));
console.log("computer.status:", await r(A.call("computer.status", {}), 1200));
console.log("node.list:", await r(A.call("node.list", {})));
console.log("system-presence:", await r(A.call("system-presence", {}), 900));
console.log("presence.query:", await r(A.call("presence.query", {}), 600));
console.log("environments.status:", await r(A.call("environments.status", {}), 600));
console.log("environments.list:", await r(A.call("environments.list", {}), 600));
