import { connect, sleep, brief } from "./probe-lib.mjs";
const A = await connect({ name: "A", scopes: ["operator.read", "operator.write"] });
const ADM = await connect({ backend: true, scopes: ["operator.read", "operator.write", "operator.admin"] });
const r = (p) => p.then((x) => JSON.stringify(x).slice(0, 400), (e) => "ERR " + e.message + " " + JSON.stringify(e.details ?? ""));
console.log("prefs.set (paired device):", await r(A.call("users.prefs.set", { entries: { "clawtrate.sidebar": { pins: ["atlas"], sections: [{ name: "Work", bots: ["pixel"] }], hidden: [], order: ["atlas", "pixel"] } } })));
console.log("prefs.get (paired device):", await r(A.call("users.prefs.get", { keys: ["clawtrate.sidebar"] })));
console.log("prefs.get (backend):", await r(ADM.call("users.prefs.get", {})));
console.log("users.self (paired device):", await r(A.call("users.self", {})));
const s = await A.call("sessions.create", { agentId: "pixel", label: `meta ${Date.now()}` });
await A.call("sessions.messages.subscribe", { key: s.key });
await (await A.send(s.key, "the zebra crossing is blue")).done;
const h1 = await A.call("chat.history", { sessionKey: s.key, limit: 5 });
const target = h1.messages.find((m) => m.role === "assistant");
console.log("message time fields:", JSON.stringify({ timestamp: target.timestamp, recordTimestampMs: target.__openclaw?.recordTimestampMs }));
const reply = await A.send(s.key, "replying to that", { replyToId: target.__openclaw.id }); await reply.done;
const h2 = await A.call("chat.history", { sessionKey: s.key, limit: 10 });
const u = h2.messages.filter((m) => m.role === "user").at(-1);
console.log("reply row keys:", Object.keys(u).join(","), "| __openclaw keys:", Object.keys(u.__openclaw ?? {}).join(","), "| replyTo-ish:", JSON.stringify(Object.fromEntries(Object.entries({ ...u, ...u.__openclaw }).filter(([k]) => /reply|quote|parent|thread/i.test(k)))));
const t0 = Date.now();
console.log("reactions.set:", await r(A.call("session.reactions.set", { sessionKey: s.key, messageId: target.__openclaw.id, emoji: "👍" })));
await sleep(500);
console.log("session.reaction event:", A.events.filter((e) => e.t >= t0 && e.event === "session.reaction").map((e) => brief(e, 300)).join(" | ") || "none");
console.log("reactions.list:", await r(A.call("session.reactions.list", { sessionKey: s.key })));
console.log("reactions remove:", await r(A.call("session.reactions.set", { sessionKey: s.key, messageId: target.__openclaw.id, emoji: "👍", remove: true })));
console.log("search:", await r(A.call("sessions.search", { query: "zebra", limit: 5 })));
console.log("search agent-scoped:", await r(A.call("sessions.search", { query: "zebra", agentId: "atlas" })));
const row = (await A.call("sessions.describe", { key: s.key })).session;
console.log("row times:", JSON.stringify(Object.fromEntries(Object.entries(row).filter(([k]) => /At$|AtMs$/.test(k)))));
await A.close(); await ADM.close();
