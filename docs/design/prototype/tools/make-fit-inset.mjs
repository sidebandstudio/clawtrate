// Writes js/fit-inset.js: for each base creature and hat, how much the equipped
// Claw is drawn smaller so it fits its circle and the Presence ring
// (docs/design/avatar-studio.md, section 4, "Fit"). Measured on the drawn
// geometry by js/fit-measure.js. The studio's check fails when the file is stale.
// Run from the repository root:  node docs/design/prototype/tools/make-fit-inset.mjs
import { writeFileSync } from "node:fs";
import { chromium, pageUrl } from "./checks/browser.mjs";

const b = await chromium.launch();
const p = await b.newPage();
await p.goto(pageUrl("avatar-studio.html") + "?chrome=0&view=chat");
await p.waitForFunction(() => !!window.ClawtrateFit);
const { table, ring } = await p.evaluate(() => ({ table: window.ClawtrateFit.generate(), ring: window.ClawtrateFit.ringLimit() }));
await b.close();
const rows = Object.keys(table)
  .sort()
  .map((key) => `    "${key}": ${table[key]},`)
  .join("\n");
writeFileSync(
  new URL("../js/fit-inset.js", import.meta.url),
  [
    "// Generated by tools/make-fit-inset.mjs from the drawn geometry (js/fit-measure.js).",
    "// Do not edit: run `node docs/design/prototype/tools/make-fit-inset.mjs`.",
    `// The Presence ring's inner edge at its tightest size: ${ring.toFixed(2)} grid units.`,
    "window.ClawtrateFitInset = {",
    "  table: {",
    rows,
    "  },",
    "};",
    "",
  ].join("\n"),
);
console.log(`${Object.keys(table).length} insets, ring ${ring.toFixed(2)}`);
