// Writes the design prototype's copy of the creature spec: the shared
// `packages/core/src/avatar.ts` with its types stripped, as a classic script
// that sets `window.ClawtrateCreatures`. The prototype pages open from disk
// with no build step, so they cannot import the TypeScript module itself.
//
//   node tools/brand/src/make-creatures.ts      (or: pnpm brand:creatures)
//
// A test (tools/brand/test/creatures.test.ts) fails when the copy is stale.

import { readFileSync, writeFileSync } from "node:fs";
import { stripTypeScriptTypes } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../../..");
export const SPEC_PATH = join(ROOT, "packages/core/src/avatar.ts");
export const CREATURES_PATH = join(ROOT, "docs/design/prototype/js/creatures.js");

/** The prototype's script for the spec's source. */
export function creaturesScript(source: string): string {
  const names = [...source.matchAll(/^export (?:const|function|let) ([A-Za-z0-9_]+)/gm)].map(
    (match) => match[1]!,
  );
  const body = stripTypeScriptTypes(source, { mode: "strip" })
    .replace(/^export /gm, "")
    .replace(/[ \t]+$/gm, "");
  return [
    "// Generated by tools/brand/src/make-creatures.ts from packages/core/src/avatar.ts.",
    "// Do not edit: change the spec and run `pnpm brand:creatures`.",
    "(function () {",
    body.trimEnd(),
    `window.ClawtrateCreatures = { ${names.join(", ")} };`,
    "})();",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(CREATURES_PATH, creaturesScript(readFileSync(SPEC_PATH, "utf8")));
  console.log(`wrote ${CREATURES_PATH.slice(ROOT.length + 1)}`);
}
